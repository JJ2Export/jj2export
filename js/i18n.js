const I18N = (() => {
  const SUPPORTED = ['en', 'pt', 'es'];
  let current = 'en';
  let dict = {};

  async function load(lang) {
    try {
      const res = await fetch(`i18n/${lang}.json`);
      if (res.ok) return await res.json();
    } catch (e) {
      console.warn("Using fallback inline I18N dict:", e);
    }
    return I18N_DATA[lang] || I18N_DATA.en;
  }

  function applyToDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });
    document.documentElement.lang = current;
  }

  function updateLangButtons() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === current);
    });
  }

  async function setLanguage(lang) {
    if (!SUPPORTED.includes(lang)) return;
    dict = await load(lang);
    current = lang;
    if (window.renderBrandCards) window.renderBrandCards(current);
    applyToDOM();
    updateLangButtons();
  }

  async function init() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
    });
    await setLanguage('en');
  }

  return { init, setLanguage, get current() { return current; } };
})();

document.addEventListener('DOMContentLoaded', I18N.init);
